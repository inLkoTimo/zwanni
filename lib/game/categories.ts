export function categoryById(id: string): Category | undefined {
  return CATEGORIES.find((category) => category.id === id);
}

/** Das Emoji einer Karte: eigenes Emoji, sonst das der Kategorie. */
export function itemEmoji(categoryId: string, item: CategoryItem): string {
  return item.emoji ?? categoryById(categoryId)?.emoji ?? "🃏";
}
